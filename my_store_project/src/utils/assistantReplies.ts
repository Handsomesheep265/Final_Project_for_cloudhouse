/** 没命中任何关键词时的兜底：承认局限 + 给一个可继续的提问方向 */
const FALLBACK =
  '这个我还没学会（现在是本地演示版，只内置了选品、排版、配色、文案几类示例回答）。\n' +
  '你可以试试问我：\n' +
  '· 「新手第一本手帐本怎么选？」\n' +
  '· 「帮我写一条关于周末的手帐文案」'

/**
 * 本地生成一条回复。
 * 命中规则时返回对应话术，否则返回兜底话术。
 */
export function replyTo(input: string): string {
  const text = input.trim().toLowerCase()
  if (!text) return FALLBACK

  const hit = RULES.find((rule) => rule.keywords.some((keyword) => text.includes(keyword)))
  return hit ? hit.reply : FALLBACK
}
